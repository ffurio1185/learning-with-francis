"""Request-local language preferences, separate from visitor identity and progress."""

from flask import Blueprint, current_app, g, redirect, render_template, request, session, url_for
from itsdangerous import BadData, URLSafeTimedSerializer
from urllib.parse import urlsplit
from flask_babel import Babel, gettext
from werkzeug.exceptions import HTTPException

from .security import valid_csrf
from .sql_display import title_text, title_language


SUPPORTED_LANGUAGES = ("en", "de")
bp = Blueprint("i18n", __name__)


def current_language():
    """Only accept our fixed locale codes; browser headers never override English."""
    language = session.get("language")
    return language if language in SUPPORTED_LANGUAGES else "en"


def clear_visit_session():
    """Discard visit identity/tokens, retaining only an explicitly chosen language."""
    language = session.get("language")
    session.clear()
    if language in SUPPORTED_LANGUAGES:
        session["language"] = language


def init_app(app):
    Babel(app, locale_selector=current_language)
    app.register_blueprint(bp)
    app.before_request(restore_language_draft)
    app.context_processor(lambda: {
        "current_language": current_language(), "status_label": status_label,
        "learning_title": title_text, "learning_title_language": title_language,
        "language_return_token": language_return_token,
        "language_draft": getattr(g, "language_draft", {}),
    })


@bp.post("/preferences/language")
def set_language():
    """Change a display preference with form protection; never open a database."""
    tokens = request.form.getlist("csrf_token")
    if len(tokens) != 1 or not valid_csrf(tokens[0]):
        return render_template("cover.html", error=gettext(
            "This form has expired. Please try again.")), 400
    languages = request.form.getlist("language")
    if len(languages) != 1 or languages[0] not in SUPPORTED_LANGUAGES:
        return render_template("cover.html", error=gettext(
            "Please choose English or German.")), 400
    returns = request.form.getlist("return_token")
    try:
        target = return_target(returns)
    except (BadData, TypeError, ValueError):
        return render_template("cover.html", error=gettext(
            "This form has expired. Please try again.")), 400
    remember_language_draft(target)
    session["language"] = languages[0]
    return redirect(target, code=303)


def status_label(value):
    """Translate labels only; database values and submitted status codes stay English."""
    labels = {"Still Learning": gettext("Still Learning"),
              "Needs Review": gettext("Needs Review"), "Completed": gettext("Completed")}
    return labels.get(value, value)


def navigation_signer():
    return URLSafeTimedSerializer(current_app.secret_key, salt="language-navigation")


def language_return_token():
    """Sign a GET destination generated by our own interface, bound to this visit."""
    if request.endpoint in ("cover", "index", "progress.index", "learning.lesson",
                            "learning.practice", "learning.quiz", "learning.results", "privacy", "impressum"):
        target = getattr(g, "language_return_path", request.path)
    elif request.endpoint == "progress.update_status":
        target = url_for("progress.index")
    else:
        target = url_for("index")
    return navigation_signer().dumps({"path": target, "visit": session.get("visit_id")})


def return_target(tokens):
    if not tokens:
        return url_for("cover")  # L1 cover controls and older open forms.
    if len(tokens) != 1 or len(tokens[0]) > 4096:
        raise ValueError("Invalid language navigation token")
    data = navigation_signer().loads(tokens[0], max_age=12 * 60 * 60)
    if not isinstance(data, dict) or data.get("visit") != session.get("visit_id"):
        raise ValueError("Language navigation belongs to another visit")
    target = data.get("path")
    if not isinstance(target, str) or not target.startswith("/") or target.startswith("//"):
        raise ValueError("Invalid language destination")
    parts = urlsplit(target)
    if parts.scheme or parts.netloc or "\\" in target or parts.fragment:
        raise ValueError("Invalid language destination")
    try:
        endpoint, _ = current_app.url_map.bind("").match(parts.path, method="GET")
    except HTTPException:
        raise ValueError("Invalid language destination") from None
    if endpoint not in ("cover", "index", "progress.index", "learning.lesson",
                         "learning.practice", "learning.quiz", "learning.results", "privacy", "impressum"):
        raise ValueError("Invalid language destination")
    # The signature prevents a browser-supplied next URL from choosing a destination.
    return target


def remember_language_draft(target):
    """Preserve small, ungraded choices; never accept scores or write learning records."""
    fields = {}
    path = urlsplit(target).path
    if path == url_for("index"):
        names = request.form.getlist("visitor_name")
        if len(names) == 1 and len(names[0]) <= 50:
            fields["visitor_name"] = names[0]
    else:
        from .subjects import SUBJECTS
        segments = path.strip("/").split("/")
        if len(segments) == 2 and segments[0] in SUBJECTS and segments[1] in ("quiz", "practice"):
            content = SUBJECTS[segments[0]]["content"]
            questions = content.QUIZ
            if segments[1] == "practice":
                positions = request.form.getlist("position")
                questions = (content.PRACTICE[int(positions[0])],) if (
                    len(positions) == 1 and positions[0] in tuple(str(i) for i in range(len(content.PRACTICE)))) else ()
            for question in questions:
                choices = request.form.getlist(question["id"])
                if len(choices) == 1 and choices[0] in question["choices"]:
                    fields[question["id"]] = choices[0]
            tokens = request.form.getlist("submission_token")
            if segments[1] == "quiz" and len(tokens) == 1 and len(tokens[0]) <= 2048:
                fields["submission_token"] = tokens[0]  # Revalidated by the normal quiz handler.
    session.pop("language_draft", None)
    if fields:
        session["language_draft"] = {"path": target, "visit": session.get("visit_id"), "fields": fields}


def restore_language_draft():
    draft = session.get("language_draft")
    if request.method == "GET" and isinstance(draft, dict):
        target = request.full_path.removesuffix("?")
        if draft.get("path") == target and draft.get("visit") == session.get("visit_id"):
            g.language_draft = session.pop("language_draft").get("fields", {})
